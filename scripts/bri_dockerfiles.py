"""Keep standalone Python image dependency stages synchronized with the root recipe."""

from __future__ import annotations

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BEGIN = "# BEGIN GENERATED BRIAREUS RUNTIME DEPENDENCIES"
END = "# END GENERATED BRIAREUS RUNTIME DEPENDENCIES"


def runtime_stage(recipe: str) -> str:
    lines = recipe.strip().splitlines()
    if not lines or not lines[0].startswith("FROM "):
        raise ValueError("The root runtime recipe must start with FROM")
    lines[0] += " AS runtime-dependencies"
    return "\n".join([
        BEGIN,
        "# Generated by scripts/bri_dockerfiles.py from Dockerfile; do not edit this stage.",
        "ARG BRI_RUNTIME_BASE=runtime-dependencies",
        *lines,
        END,
        "",
    ])


def standalone_dockerfile(source: str, recipe: str) -> str:
    if source.startswith(BEGIN):
        _prefix, separator, source = source.partition(END + "\n")
        if not separator:
            raise ValueError("The generated runtime stage is incomplete")
        source = source.lstrip("\n")
    elif source.startswith("ARG BRI_RUNTIME_BASE="):
        source = source.split("\n", 1)[1]
    else:
        raise ValueError("The source image does not declare its runtime base")
    return runtime_stage(recipe) + source


def image_paths() -> tuple[Path, ...]:
    return tuple(
        path for path in sorted((ROOT / "deploy").rglob("Dockerfile"))
        if path.read_text(encoding="utf-8").startswith((BEGIN, "ARG BRI_RUNTIME_BASE="))
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    recipe = (ROOT / "Dockerfile").read_text(encoding="utf-8")
    paths = image_paths()
    if not paths:
        raise ValueError("No Briareus Python source images were found")
    for path in paths:
        source = path.read_text(encoding="utf-8")
        expected = standalone_dockerfile(source, recipe)
        if arguments.check:
            if source != expected:
                raise ValueError(f"Source image runtime stage is stale: {path.relative_to(ROOT)}")
        else:
            path.write_text(expected, encoding="utf-8")
    print(f"Verified {len(paths)} standalone Python image dependency stages")


if __name__ == "__main__":
    main()
