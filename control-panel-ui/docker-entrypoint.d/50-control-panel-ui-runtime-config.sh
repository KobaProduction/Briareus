#!/bin/sh
set -eu

preview="$(printf '%s' "${CONTROL_PANEL_UI_PREVIEW:-false}" | tr '[:upper:]' '[:lower:]')"

export CONTROL_PANEL_UI_PREVIEW="$preview"
export CONTROL_PANEL_UI_TELEMETRY_ENABLED="${CONTROL_PANEL_UI_TELEMETRY_ENABLED:-true}"
export CONTROL_PANEL_UI_TELEMETRY_ENDPOINT="${CONTROL_PANEL_UI_TELEMETRY_ENDPOINT:-/api/telemetry}"
export CONTROL_PANEL_UI_TELEMETRY_SAMPLE_RATE="${CONTROL_PANEL_UI_TELEMETRY_SAMPLE_RATE:-1}"
export CONTROL_PANEL_UI_EVENTS_MODE="${CONTROL_PANEL_UI_EVENTS_MODE:-hybrid}"
export CONTROL_PANEL_UI_EVENTS_URL="${CONTROL_PANEL_UI_EVENTS_URL:-/api/realtime}"

envsubst '${CONTROL_PANEL_UI_PREVIEW} ${CONTROL_PANEL_UI_TELEMETRY_ENABLED} ${CONTROL_PANEL_UI_TELEMETRY_ENDPOINT} ${CONTROL_PANEL_UI_TELEMETRY_SAMPLE_RATE} ${CONTROL_PANEL_UI_EVENTS_MODE} ${CONTROL_PANEL_UI_EVENTS_URL}' \
    < /usr/share/nginx/html/runtime-config.template.js \
    > /usr/share/nginx/html/runtime-config.js
